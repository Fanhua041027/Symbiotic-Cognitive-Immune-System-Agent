"""HTML report generator for immune system performance.

Produces self-contained HTML reports with embedded CSS for
benchmark results, training progress, and system metrics.
"""

import json
import os
from datetime import datetime, timezone
from typing import Any

from core.logger import setup_logger

logger = setup_logger("reports")

REPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "reports")


def _bar_html(label: str, value: float, max_value: float = 100.0,
              color: str = "#1a73e8", width: int = 300) -> str:
    """Render a single horizontal bar as HTML/CSS."""
    pct = min(value / max_value * 100, 100) if max_value > 0 else 0
    return f"""<div style="display:flex;align-items:center;margin:4px 0;gap:8px">
    <span style="width:140px;font-size:0.8rem;color:#536471;text-align:right;flex-shrink:0">{label}</span>
    <div style="flex:1;height:20px;background:#e8eaed;border-radius:10px;overflow:hidden;max-width:{width}px">
        <div style="height:100%;width:{pct:.0f}%;background:{color};border-radius:10px;transition:width 0.3s"></div>
    </div>
    <span style="width:50px;font-size:0.8rem;font-weight:600;color:#0f1419">{value:.1f}%</span>
</div>"""


